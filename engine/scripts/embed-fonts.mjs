#!/usr/bin/env node
// Writes src/ui/fontData.ts: the three OFL/Apache fonts as base64 @font-face data, so renders never wait on a font
// download (the 2D Documentary Skill, 5.0: "Embed fonts in the bundle ... a font wait can hang a render tab").
// Run after changing font versions:  node scripts/embed-fonts.mjs
import fs from "node:fs";
const fonts = {
  Caveat: "node_modules/@fontsource/caveat/files/caveat-latin-600-normal.woff2",
  PermanentMarker: "node_modules/@fontsource/permanent-marker/files/permanent-marker-latin-400-normal.woff2",
  PatrickHand: "node_modules/@fontsource/patrick-hand/files/patrick-hand-latin-400-normal.woff2",
};
let out = "// GENERATED by scripts/embed-fonts.mjs. Fonts: Caveat (OFL-1.1), Permanent Marker (Apache-2.0), Patrick Hand (OFL-1.1).\n";
out += "export const FONT_CSS = [\n";
for (const [name, file] of Object.entries(fonts)) {
  const b64 = fs.readFileSync(file).toString("base64");
  out += `  "@font-face{font-family:'${name}';src:url(data:font/woff2;base64,${b64}) format('woff2');font-display:block;}",\n`;
}
out += "].join(\"\\n\");\n";
fs.writeFileSync("src/ui/fontData.ts", out);
console.log("wrote src/ui/fontData.ts", out.length, "chars");
